"""Does an actual estimator reach the Cramer-Rao session counts? (AIL-R29-01, R29 P1)

``identifiability`` reports Cramer-Rao bounds: a lower bound on the variance of
UNBIASED regular estimators. Whether a real estimator attains them at a given
number of sessions is a separate, empirical question, and a biased estimator
is not bound by them at all. This module answers it for the maximum-likelihood
estimator (MLE) inside the synthetic model, by Monte Carlo:

1. ``sample_counts`` draws the outcome counts of N independent sessions
   exactly (multinomial by sequential binomials; the counts are a sufficient
   statistic, so no session is simulated one by one);
2. ``fit_mle`` maximises the multinomial log-likelihood by Fisher scoring
   with step halving inside the parameter domain, from a given start;
3. ``estimator_calibration`` repeats both and measures, per parameter, the
   relative bias, the empirical relative standard error and RMSE, the ratio
   to the Cramer-Rao relative standard error and the coverage of the Wald
   interval ``estimate +- z * SE`` with the expected Fisher information at
   the estimate -- each with its Monte-Carlo standard error, and with every
   failed fit counted, never dropped silently.

Scope (``ESTIMATOR_SCOPE``): model-internal, one parameter point, one design,
one estimator; the data are generated by the same model that is fitted, so
model error is excluded by construction. A good result says "the MLE behaves
as the asymptotic theory predicts at this N in this model", nothing about an
instrument.
"""

from __future__ import annotations

import random
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from math import isfinite, log, sqrt

from .identifiability import SESSIONS_SCOPE, Calibration, Design, _check_free, _leaves, identifiability

__all__ = [
    "ESTIMATOR_SCOPE",
    "Fit",
    "ParameterCalibration",
    "EstimatorCalibration",
    "sample_counts",
    "fit_mle",
    "estimator_calibration",
    "sd_mcse",
]

ESTIMATOR_SCOPE = "MONTE_CARLO_MLE_MODEL_INTERNAL_ONE_POINT"
Z95 = 1.959963984540054  # two-sided 95 % normal quantile
MAX_SESSIONS = 10**12
MAX_REPLICATIONS = 100_000
_MAX_ITER = 100
_REL_STEP_TOL = 1e-10


def _int_in(v, lo: int, hi: int) -> bool:
    return isinstance(v, int) and not isinstance(v, bool) and lo <= v <= hi


def sd_mcse(xs) -> float:
    """Monte-Carlo standard error of the sample standard deviation of ``xs`` (at least 4 values).

    Moment-based, without a normality assumption: with the central moments m2, m4,
    ``Var(s^2) ~ (m4 - m2^2 (m-3)/(m-1)) / m`` and, by the delta method,
    ``se(s) = se(s^2) / (2 s)``. For normal data (m4 = 3 m2^2) this is about
    ``s / sqrt(2 (m-1))``, the formula of Morris, White & Crowther (2019,
    Stat. Med. 38:2074, doi:10.1002/sim.8086, Table 6); heavy tails make it larger.
    """
    xs = [float(x) for x in xs]
    m = len(xs)
    if m < 4 or not all(isfinite(x) for x in xs):
        raise ValueError("sd_mcse needs at least 4 finite values")
    mean = sum(xs) / m
    m2 = sum((x - mean) ** 2 for x in xs) / m
    if m2 == 0.0:
        return 0.0
    m4 = sum((x - mean) ** 4 for x in xs) / m
    var_s2 = max(m4 - m2 * m2 * (m - 3) / (m - 1), 0.0) / m
    s = sqrt(m2 * m / (m - 1))
    # var_s2 is already the variance of the UNBIASED s^2; normal data: 2 sigma^4/(m-1) -> sigma/sqrt(2(m-1))
    return sqrt(var_s2) / (2 * s)


def sample_counts(
    calibration: Calibration, design: Design, sessions: int, rng: random.Random
) -> dict[tuple[int, ...], int]:
    """Outcome counts of ``sessions`` independent sessions (exact multinomial draw)."""
    if not _int_in(sessions, 1, MAX_SESSIONS):
        raise ValueError(f"sessions must be an int in 1..{MAX_SESSIONS}")
    if not isinstance(rng, random.Random):
        raise ValueError("rng must be a random.Random instance (seeded for reproducibility)")
    probs = [(o, p.v) for o, p in _leaves(calibration, design, ())]
    if not all(isfinite(p) and p >= 0 for _, p in probs) or abs(sum(p for _, p in probs) - 1.0) > 1e-12:
        raise ArithmeticError("outcome probabilities are not a distribution")
    counts: dict[tuple[int, ...], int] = {}
    left, mass = sessions, 1.0
    for k, (o, p) in enumerate(probs):
        if left == 0:
            break
        if k == len(probs) - 1 or p >= mass:
            n = left  # the last outcome takes the rest; guards against rounding in the remaining mass
        else:
            n = rng.binomialvariate(left, p / mass) if p > 0 else 0
        if n:
            counts[o] = n
        left -= n
        mass -= p
    return counts


@dataclass(frozen=True)
class Fit:
    values: tuple[float, ...]  # estimates of the free parameters, canonical order
    std_errors: tuple[float, ...] | None  # sqrt(diag (N F(estimate))^-1); None if F is singular
    converged: bool
    iterations: int
    log_likelihood: float
    reason: str  # "converged" or why not


def _solve(a: list[list[float]], b: list[float]) -> list[float] | None:
    """Gaussian elimination with partial pivoting; None if (numerically) singular."""
    n = len(b)
    m = [list(a[i]) + [b[i]] for i in range(n)]
    scale = max(abs(m[i][i]) for i in range(n)) or 1.0
    for c in range(n):
        piv = max(range(c, n), key=lambda r: abs(m[r][c]))
        if abs(m[piv][c]) <= 1e-14 * scale:
            return None
        m[c], m[piv] = m[piv], m[c]
        for r in range(n):
            if r != c and m[r][c] != 0.0:
                f = m[r][c] / m[c][c]
                m[r] = [x - f * y for x, y in zip(m[r], m[c], strict=True)]
    return [m[i][n] / m[i][i] for i in range(n)]


def _inverse_diag(a: list[list[float]]) -> list[float] | None:
    n = len(a)
    out = []
    for i in range(n):
        col = _solve(a, [1.0 if j == i else 0.0 for j in range(n)])
        if col is None or not col[i] > 0:
            return None
        out.append(col[i])
    return out


def _check_counts(calibration: Calibration, design: Design, counts: Mapping) -> int:
    if not isinstance(counts, Mapping) or not counts:
        raise ValueError("counts must be a non-empty mapping outcome -> count")
    outcomes = {o for o, _ in _leaves(calibration, design, ())}
    for o, n in counts.items():
        if o not in outcomes:
            raise ValueError(f"outcome {o!r} is not an outcome of this design")
        if not _int_in(n, 0, MAX_SESSIONS):
            raise ValueError("every count must be an int >= 0")
    total = sum(counts.values())
    if not 1 <= total <= MAX_SESSIONS:
        raise ValueError("the counts must add up to 1..MAX_SESSIONS sessions")
    return total


def fit_mle(start: Calibration, design: Design, free: Iterable[str], counts: Mapping) -> Fit:
    """Maximum-likelihood estimate of ``free`` from outcome ``counts``, by Fisher scoring from ``start``.

    The parameters not in ``free`` stay at their values in ``start``. Each
    step is halved until the new point is a valid calibration with every free
    parameter > 0 and the log-likelihood does not decrease. A fit that leaves
    the interior, stalls or exceeds the iteration limit is returned with
    ``converged = False`` and the reason; it is never silently accepted.
    """
    free = _check_free(start, free)
    total = _check_counts(start, design, counts)
    k = len(free)

    def evaluate(cal: Calibration):
        ll, score = 0.0, [0.0] * k
        fim = [[0.0] * k for _ in range(k)]
        for o, p in _leaves(cal, design, free):
            n = counts.get(o, 0)
            if p.v <= 0.0:
                if n:
                    return None  # an observed outcome has probability 0 here: log-likelihood -inf
                continue
            if n:
                ll += n * log(p.v)
            for i in range(k):
                gi = p.g[i] / p.v
                if n:
                    score[i] += n * gi
                if gi:
                    row = fim[i]
                    for j in range(k):
                        row[j] += total * gi * p.g[j]
        return ll, score, fim

    theta = {f: start.parameters()[f] for f in free}
    cal = start
    cur = evaluate(cal)
    if cur is None:
        return Fit(tuple(theta.values()), None, False, 0, float("-inf"), "start has log-likelihood -inf")
    for it in range(1, _MAX_ITER + 1):
        ll, score, fim = cur
        step = _solve(fim, score)
        if step is None:
            return Fit(tuple(theta.values()), None, False, it, ll, "singular Fisher information")
        t = 1.0
        while True:
            new = {f: theta[f] + t * s for f, s in zip(free, step, strict=True)}
            cand = None
            if all(v > 0 for v in new.values()):
                try:
                    cal_new = start.with_values(new)
                    cand = evaluate(cal_new)
                except (ValueError, ArithmeticError):
                    cand = None
            if cand is not None and cand[0] >= ll - 1e-9 * abs(ll):
                break
            t *= 0.5
            if t < 2**-40:
                return Fit(tuple(theta.values()), None, False, it, ll, "no admissible ascent step (boundary)")
        rel = max(abs(t * s) / abs(new[f]) for f, s in zip(free, step, strict=True))
        theta, cal, cur = new, cal_new, cand
        if rel < _REL_STEP_TOL:
            diag = _inverse_diag(cur[2])
            se = None if diag is None else tuple(sqrt(d) for d in diag)
            return Fit(tuple(theta.values()), se, True, it, cur[0], "converged")
    return Fit(tuple(theta.values()), None, False, _MAX_ITER, cur[0], "iteration limit")


@dataclass(frozen=True)
class ParameterCalibration:
    name: str
    true_value: float
    crlb_rse: float  # Cramer-Rao relative standard error at this N (unbiased regular estimators)
    relative_bias: float  # (mean estimate - true) / true, over converged fits
    relative_bias_mcse: float  # Monte-Carlo standard error of relative_bias
    empirical_rse: float  # sample standard deviation / true
    empirical_rrmse: float  # sqrt(mean (estimate - true)^2) / true
    rse_ratio: float  # empirical_rse / crlb_rse; about 1 when the MLE is efficient at this N
    coverage: float  # share of converged fits whose Wald interval contains the true value
    coverage_mcse: float
    # Appended in R30 with defaults (positional construction of the ten fields above unchanged).
    # crlb_rse is a Cramer-Rao figure, so it travels with the same scope as every session count
    # (AIL4-01 / AIL-01): a lower bound for unbiased regular estimators only.
    sessions_scope: str = SESSIONS_SCOPE
    # Monte-Carlo standard error of empirical_rse, moment-based (no normality assumption):
    # Var(s^2) ~ (m4 - s^4 (m-3)/(m-1)) / m, delta method se(s) = se(s^2) / (2 s).
    empirical_rse_mcse: float = float("nan")
    # Coverage over ALL replications, not only the converged ones (survivor selection, AIL4-03):
    # low counts every failed fit as a miss, high as a hit; the converged-only coverage lies in between.
    coverage_all_low: float = float("nan")
    coverage_all_high: float = float("nan")


@dataclass(frozen=True)
class EstimatorCalibration:
    design: Design
    free: tuple[str, ...]
    sessions: int
    replications: int
    converged: int
    failures: tuple[tuple[str, int], ...]  # reason -> count; failed fits are reported, not hidden
    seed: int
    start_offset: float  # every free parameter starts at true * (1 + start_offset)
    level: float  # nominal coverage of the Wald interval
    parameters: tuple[ParameterCalibration, ...]
    scope: str  # ESTIMATOR_SCOPE
    notes: tuple[str, ...]


def estimator_calibration(
    truth: Calibration,
    design: Design,
    free: Iterable[str],
    sessions: int,
    replications: int,
    seed: int,
    start_offset: float = 0.2,
) -> EstimatorCalibration:
    """Monte-Carlo behaviour of the MLE at ``sessions`` sessions, against the Cramer-Rao bound.

    The fit starts at ``true * (1 + start_offset)`` for every free parameter
    (never at the truth). The random stream is ``random.Random(seed)``; the
    same arguments give the same numbers.
    """
    free = _check_free(truth, free)
    if not _int_in(sessions, 1, MAX_SESSIONS):
        raise ValueError(f"sessions must be an int in 1..{MAX_SESSIONS}")
    if not _int_in(replications, 2, MAX_REPLICATIONS):
        raise ValueError(f"replications must be an int in 2..{MAX_REPLICATIONS}")
    if not _int_in(seed, 0, 2**63 - 1):
        raise ValueError("seed must be a non-negative int")
    if isinstance(start_offset, bool) or not isinstance(start_offset, (int, float)) or not isfinite(start_offset):
        raise ValueError("start_offset must be a finite number")
    if not -1 < start_offset:
        raise ValueError("start_offset must be > -1 (start values stay positive)")
    report = identifiability(truth, design, free)
    if not report.locally_identifiable:
        raise ValueError(f"design is {report.verdict} for these parameters: the MLE is not defined locally")
    true = {f: truth.parameters()[f] for f in free}
    if any(v == 0.0 for v in true.values()):
        raise ValueError("every free parameter must be non-zero (relative errors, interior point)")
    start = truth.with_values({f: v * (1 + start_offset) for f, v in true.items()})
    rng = random.Random(seed)
    fits, failures = [], {}
    for _ in range(replications):
        counts = sample_counts(truth, design, sessions, rng)
        fit = fit_mle(start, design, free, counts)
        if fit.converged and fit.std_errors is not None:
            fits.append(fit)
        else:
            reason = fit.reason if not fit.converged else "singular Fisher information at the estimate"
            failures[reason] = failures.get(reason, 0) + 1
    params = []
    m = len(fits)
    for i, f in enumerate(free):
        tv = true[f]
        crlb = report.relative_crlb[i] / sqrt(sessions)
        if m < 2:
            nan = float("nan")
            params.append(ParameterCalibration(f, tv, crlb, nan, nan, nan, nan, nan, nan, nan))
            continue
        xs = [fit.values[i] for fit in fits]
        mean = sum(xs) / m
        sd = sqrt(sum((x - mean) ** 2 for x in xs) / (m - 1))
        rmse = sqrt(sum((x - tv) ** 2 for x in xs) / m)
        hits = sum(abs(fit.values[i] - tv) <= Z95 * fit.std_errors[i] for fit in fits)
        hit = hits / m
        params.append(
            ParameterCalibration(
                f,
                tv,
                crlb,
                (mean - tv) / abs(tv),
                sd / sqrt(m) / abs(tv),
                sd / abs(tv),
                rmse / abs(tv),
                (sd / abs(tv)) / crlb,
                hit,
                sqrt(max(hit * (1 - hit), 1e-300) / m),
                SESSIONS_SCOPE,
                sd_mcse(xs) / abs(tv) if m >= 4 else float("nan"),  # 2..3 fits: no fourth moment
                hits / replications,
                (hits + replications - m) / replications,
            )
        )
    notes = (
        "model-internal Monte Carlo: data generated by the fitted model, one parameter point, one design, MLE only",
        "crlb_rse bounds unbiased regular estimators; the MLE is biased at finite N, so rse_ratio < 1 does not "
        "contradict the bound and rse_ratio ~ 1 does not prove efficiency elsewhere",
        "bias, RSE, coverage and failures are separate measures, each with its Monte-Carlo error; coverage is "
        "over converged fits, coverage_all_low/high bound it over all replications (failed fits as miss/hit)",
    )
    return EstimatorCalibration(
        design,
        free,
        sessions,
        replications,
        m,
        tuple(sorted(failures.items())),
        seed,
        float(start_offset),
        0.95,
        tuple(params),
        ESTIMATOR_SCOPE,
        notes,
    )
